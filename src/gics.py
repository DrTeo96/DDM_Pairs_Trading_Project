def load_gics() -> pd.DataFrame:
    """data/gics.csv with English names. Fails if a name is missing from the tables, instead of leaving it in Italian."""
    g = pd.read_csv(GICS).set_index("ticker")
    for col, table in (("industry_group", INDUSTRY_GROUP), ("sub_industry", SUB_INDUSTRY)):
        missing = sorted(set(g[col].dropna()) - set(table))
        if missing:
            raise KeyError(f"{col}: no English name for {missing}")
        g[col] = g[col].map(table)
    return g
